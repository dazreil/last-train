#!/usr/bin/env node
/**
 * Build data/popularity.json from the ORR Origin-Destination Matrix.
 *
 * The picker lists every direct destination nearest first, which is route order — and
 * leaves the place most people are actually going wherever the route puts it. From
 * Upminster, Fenchurch Street is twenty-one minutes away and last in the West group,
 * while it is one of the two busiest journeys anyone makes from there. This file is how
 * the picker knows that.
 *
 * Run once a year, when ORR publishes the next matrix (early December):
 *
 *   node scripts/generate-popularity.mjs --file ~/Downloads/ODM_for_RDM_2024-25.csv
 *
 * The matrix is free from the Rail Data Marketplace, "Origin and destination matrix (ODM)
 * <year>", under the Open Government Licence v3.0 — which requires the attribution this
 * file carries and the app shows.
 */

import { writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { busiest, readOdm } from './lib/odm.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

/**
 * How many destinations per station to keep.
 *
 * Measured, not chosen: checked against every station's real direct destinations from a
 * weekday timetable, the top three direct destinations came out
 *
 *   keep  5 -> 40 stations wrong    keep 15 -> 1 wrong, of 2,456
 *   keep 10 ->  3 stations wrong    keep 50 -> 0 wrong, but 3x the size
 *
 * Fifteen is where the curve flattens. The one station it misses has a third-busiest
 * direct destination buried below fifteen places it cannot reach directly.
 */
const KEEP = 15;

const args = process.argv.slice(2);
const at = args.indexOf('--file');
if (at === -1 || !args[at + 1]) {
  console.error('\n  --file <path>   the ODM CSV from the Rail Data Marketplace\n');
  process.exit(1);
}
const path = resolve(args[at + 1].replace(/^~/, homedir()));

const { flows, year, rows } = await readOdm(path);
// "20242025" -> "2024-25", the way ORR names its own years.
const label = /^\d{8}$/.test(year ?? '') ? `${year.slice(0, 4)}-${year.slice(6)}` : year;

const ranked = busiest(flows, KEEP);
const stations = Object.fromEntries(
  Object.entries(ranked)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([crs, list]) => [crs, list.map(([to]) => to).join(' ')])
);

const out = {
  generatedAt: new Date().toISOString(),
  financialYear: label,
  note: 'Generated by scripts/generate-popularity.mjs. Never hand-edited.',
  source: `ORR Origin-Destination Matrix ${label}`,
  attribution:
    'Contains data from the Office of Rail and Road, licensed under the Open Government Licence v3.0.',
  /**
   * Each station's busiest destinations, busiest first, as space-separated codes.
   * Ranks only: the counts are not needed to order a list, and without them the file is
   * a fifth of the size.
   */
  stations,
};

const file = join(ROOT, 'data', 'popularity.json');
writeFileSync(file, `${JSON.stringify(out, null, 1)}\n`);
const bytes = Buffer.byteLength(JSON.stringify(out, null, 1));
console.log(`\n  ${label}: ${rows.toLocaleString('en-GB')} rows, ${Object.keys(stations).length} stations`);
console.log(`  kept ${KEEP} per station -> data/popularity.json, ${(bytes / 1024).toFixed(0)} KiB`);
console.log(`  UPM: ${stations.UPM}\n`);
